import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it } from 'vitest'
import App from '../../App'
import { useProject } from '../../store/project'
import { resetV2, useV2 } from '../store'

function at(path: string) {
  render(<MemoryRouter initialEntries={[path]}><App /></MemoryRouter>)
}

describe('v2 screens', () => {
  beforeEach(() => { localStorage.clear(); resetV2(); useProject.getState().reset() })

  it('v1 is untouched: its routes still show the v1 screens, with a link to v2', () => {
    at('/')
    expect(screen.getByRole('link', { name: 'Open v2' })).toHaveAttribute('href', '/v2')
    expect(screen.getByRole('link', { name: /Palette/ })).toBeInTheDocument()
    expect(screen.queryByText('Baseline v2')).not.toBeInTheDocument()
  })

  it('/v2 shows Default\'s 16-step ramps and a way back to v1', () => {
    at('/v2')
    expect(screen.getByText('Baseline v2')).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Back to v1' })).toHaveAttribute('href', '/')
    const primary = within(screen.getByRole('main')).getByRole('region', { name: 'Primary' })
    expect(within(primary).getAllByRole('img')).toHaveLength(16)
    expect(within(primary).getByRole('img', { name: 'Primary 10, #9D00D6' })).toBeInTheDocument()
  })

  it('switching to Untitled shows 11-step ramps named 50 to 950', async () => {
    at('/v2')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    const brand = within(screen.getByRole('main')).getByRole('region', { name: 'Brand' })
    expect(within(brand).getAllByRole('img')).toHaveLength(11)
    expect(within(brand).getByRole('img', { name: 'Brand 600, #7F56D9' })).toBeInTheDocument()
    expect(within(brand).getByRole('img', { name: /^Brand 950/ })).toBeInTheDocument()
    expect(document.title).toContain('Untitled')
  })

  it('a typed colour regenerates only that ramp, and a theme keeps its own colours', async () => {
    at('/v2')
    fireEvent.change(document.getElementById('f-primary')!, { target: { value: '#0EA5E9' } })
    const main = within(screen.getByRole('main'))
    expect(main.getByRole('img', { name: 'Primary 10, #0EA5E9' })).toBeInTheDocument()
    expect(within(main.getByRole('region', { name: 'Info' })).getByRole('img', { name: /^Info 10, #2563EB/ })).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'New' }))
    expect((screen.getByLabelText('Theme') as HTMLSelectElement).selectedOptions[0].textContent).toBe('Base copy')
    fireEvent.change(document.getElementById('f-primary')!, { target: { value: '#111111' } })
    await userEvent.selectOptions(screen.getByLabelText('Theme'), 'base')
    expect(main.getByRole('img', { name: 'Primary 10, #0EA5E9' })).toBeInTheDocument()
  })

  it('tokens: groups, remap by picking a ramp step, and reset', async () => {
    at('/v2/tokens')
    expect(screen.getByRole('region', { name: 'Backgrounds' })).toBeInTheDocument()
    expect(screen.getByRole('region', { name: 'Text' })).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: /^bg-fill, Light: primary\/10\. Change/ }))
    const dialog = screen.getByRole('dialog', { name: 'bg-fill, Light' })
    await userEvent.click(within(dialog).getByRole('button', { name: 'Info' }))
    await userEvent.click(within(dialog).getByRole('button', { name: 'Info 8' }))
    expect(screen.getByRole('button', { name: /^bg-fill, Light: info\/8 \(changed\)/ })).toBeInTheDocument()
    await userEvent.click(within(dialog).getByRole('button', { name: 'Reset this value' }))
    expect(screen.getByRole('button', { name: /^bg-fill, Light: primary\/10\. Change/ })).toBeInTheDocument()
  })

  it('tokens: Untitled\'s own groups and 11-step pickers', async () => {
    at('/v2/tokens')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    for (const g of ['Background', 'Text', 'Foreground', 'Border', 'Utility']) expect(screen.getByRole('region', { name: g })).toBeInTheDocument()
    await userEvent.click(within(screen.getByRole('region', { name: 'Text' })).getAllByRole('button', { name: /^Colors\/Text\/text-primary \(900\), Light mode/ })[0])
    const dialog = screen.getByRole('dialog', { name: /text-primary \(900\), Light mode/ })
    await userEvent.click(within(dialog).getByRole('button', { name: 'Neutral' }))
    expect(within(dialog).getAllByRole('button', { name: /^Neutral \d+$/ })).toHaveLength(11)
  })

  it('export: CSS by default, JSON for the plugin, collections can be left out', async () => {
    at('/v2')
    await userEvent.click(screen.getByRole('button', { name: 'Export' }))
    const dialog = screen.getByRole('dialog', { name: /Export Default/ })
    expect(within(dialog).getByLabelText('Export preview')).toHaveTextContent('--primary-1:')
    expect(within(dialog).getByText(/ tokens · default-base\.css/)).toBeInTheDocument()
    await userEvent.click(within(dialog).getByRole('checkbox', { name: /Primitives/ }))
    expect(within(dialog).getByLabelText('Export preview')).not.toHaveTextContent('--primary-1:')
    await userEvent.click(within(dialog).getByRole('radio', { name: /Design tokens JSON/ }))
    expect(within(dialog).getByLabelText('Export preview')).toHaveTextContent('"Semantic"')
    await userEvent.keyboard('{Escape}')
    expect(screen.queryByRole('dialog', { name: /Export Default/ })).not.toBeInTheDocument()
  })

  it('type: Default\'s scale in three groups, driven by base size and ratio', async () => {
    at('/v2/type')
    for (const g of ['HEADING', 'BODY', 'LABEL']) expect(screen.getByRole('region', { name: g })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'body-md, 14px, line 24px' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Base size'), { target: { value: '16' } })
    expect(screen.getByRole('button', { name: 'body-md, 16px, line 24px' })).toBeInTheDocument()
    await userEvent.selectOptions(screen.getByLabelText('Scale ratio'), '1.25')
    expect(useV2.getState().themes.default[0].type).toMatchObject({ base: 16, ratio: 1.25 })
    const heading = screen.getByLabelText('Heading font')
    await userEvent.clear(heading)
    await userEvent.type(heading, 'Inter')
    expect(useV2.getState().themes.default[0].type?.headingFont).toBe('Inter')
  })

  it('type: a single step can be set by hand and put back', async () => {
    at('/v2/type')
    await userEvent.click(screen.getByRole('button', { name: /^body-md, 14px/ }))
    const size = screen.getByLabelText('SIZE (PX)')
    await userEvent.clear(size)
    await userEvent.type(size, '20')
    expect(screen.getByRole('button', { name: /^body-md, 20px/ })).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Reset this step' }))
    expect(screen.getByRole('button', { name: /^body-md, 14px/ })).toBeInTheDocument()
  })

  it('type: Untitled\'s named steps with their exact sizes, and no scale controls', async () => {
    at('/v2/type')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    expect(screen.getByRole('region', { name: 'TEXT' })).toBeInTheDocument()
    expect(screen.getByRole('region', { name: 'DISPLAY' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'text-md, 16px, line 24px' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'display-2xl, 72px, line 90px' })).toBeInTheDocument()
    expect(screen.queryByLabelText('Scale ratio')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('LETTER SPACING (EM)')).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: /^text-md, 16px/ }))
    expect(screen.queryByLabelText('LETTER SPACING (EM)')).not.toBeInTheDocument()
    const size = screen.getByLabelText('SIZE (PX)')
    await userEvent.clear(size)
    await userEvent.type(size, '18')
    expect(screen.getByRole('button', { name: 'text-md, 18px, line 27px' })).toBeInTheDocument()
  })

  it('sizes: Default\'s spacing scale and grid, with values that can be set and added', async () => {
    at('/v2/sizes')
    expect(screen.getByRole('region', { name: 'Spacing scale' })).toBeInTheDocument()
    expect(screen.getByRole('region', { name: 'Grid by breakpoint' })).toBeInTheDocument()
    const grid = within(screen.getByRole('region', { name: 'Grid by breakpoint' }))
    expect(grid.getByLabelText('grid/columns MD')).toHaveValue(8)
    fireEvent.change(grid.getByLabelText('grid/columns MD'), { target: { value: '6' } })
    expect(useV2.getState().themes.default[0].overrides['Grid::grid/columns|md']).toEqual({ value: 6 })
    fireEvent.blur(grid.getByLabelText('grid/columns MD'))
    await userEvent.click(within(screen.getByRole('region', { name: 'Grid by breakpoint' })).getByRole('button', { name: 'Reset grid/columns' }))
    expect(grid.getByLabelText('grid/columns MD')).toHaveValue(8)
    await userEvent.type(screen.getByLabelText('Add a value in px to Spacing scale'), '36')
    await userEvent.click(screen.getByRole('button', { name: 'Add' }))
    expect(screen.getByLabelText('space/36 Value')).toHaveValue(36)
    await userEvent.click(screen.getByRole('button', { name: 'Remove space/36' }))
    expect(screen.queryByLabelText('space/36 Value')).not.toBeInTheDocument()
    await userEvent.type(screen.getByLabelText('Add a value in px to Spacing scale'), '999')
    await userEvent.click(screen.getByRole('button', { name: 'Add' }))
    expect(screen.getByRole('alert')).toBeInTheDocument()
  })

  it('sizes: Untitled\'s five sections, tokens that follow the scale', async () => {
    at('/v2/sizes')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    for (const t of ['Scale', 'Spacing tokens', 'Radius', 'Widths', 'Containers']) expect(screen.getByRole('region', { name: t })).toBeInTheDocument()
    const follows = screen.getByLabelText('spacing-xs follows') as HTMLSelectElement
    expect(follows.value).toBe('_Primitives::Spacing/1 (4px)')
    await userEvent.selectOptions(follows, '_Primitives::Spacing/2 (8px)')
    expect(screen.getByLabelText('spacing-xs Mode 1')).toHaveValue(8)
    fireEvent.change(screen.getByLabelText('Spacing/2 (8px) Style'), { target: { value: '10' } })
    expect(screen.getByLabelText('spacing-xs Mode 1')).toHaveValue(10)
    fireEvent.change(screen.getByLabelText('spacing-xs Mode 1'), { target: { value: '9' } })
    expect((screen.getByLabelText('spacing-xs follows') as HTMLSelectElement).value).toBe('')
    fireEvent.blur(screen.getByLabelText('spacing-xs Mode 1'))
    await userEvent.click(screen.getByRole('button', { name: 'Reset spacing-xs' }))
    expect(screen.getByLabelText('spacing-xs Mode 1')).toHaveValue(4)
    expect(screen.getByLabelText('radius-full Mode 1')).toHaveValue(9999)
  }, 20000)

  it('export: with several themes, all of them go in one file, or only the active one', async () => {
    at('/v2')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    await userEvent.click(screen.getByRole('button', { name: 'New' }))
    fireEvent.change(document.getElementById('f-brand')!, { target: { value: '#0EA5E9' } })
    await userEvent.click(screen.getByRole('button', { name: 'Export' }))
    const dialog = screen.getByRole('dialog', { name: /Export Untitled, 2 themes/ })
    expect(within(dialog).getByRole('radio', { name: /All themes in one file \(2\)/ })).toBeChecked()
    expect(within(dialog).getByText(/ × 2 themes · untitled-themes\.css/)).toBeInTheDocument()
    await userEvent.click(within(dialog).getByRole('checkbox', { name: /1\. Color modes/ }))
    await userEvent.click(within(dialog).getByRole('checkbox', { name: /6\. Typography/ }))
    for (const c of ['2. Radius', '3. Spacing', '4. Widths', '5. Containers']) await userEvent.click(within(dialog).getByRole('checkbox', { name: new RegExp(c.replace('.', '\\.')) }))
    const preview = within(dialog).getByLabelText('Export preview')
    expect(preview).toHaveTextContent('/* Theme: Base */')
    await userEvent.click(within(dialog).getByRole('radio', { name: /Design tokens JSON/ }))
    expect(preview).toHaveTextContent('"Base copy"')
    await userEvent.click(within(dialog).getByRole('radio', { name: /^Only Base copy/ }))
    expect(preview).not.toHaveTextContent('"Base copy"')
    expect(within(dialog).getByText(/ · untitled-theme-2\.json/)).toBeInTheDocument()
  })

  it('elevation: a tab for systems that have shadows, with presets, layers and levels', async () => {
    at('/v2/elevation')
    expect(screen.getByRole('link', { name: 'Elevation' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Soft ambient' })).toHaveAttribute('aria-pressed', 'true')
    expect(screen.getAllByRole('region', { name: /^Level / })).toHaveLength(5)
    await userEvent.click(screen.getByRole('button', { name: 'Carbon' }))
    expect(screen.getAllByRole('region', { name: /^Level / })).toHaveLength(3)
    const blur = screen.getByLabelText('low layer 1 Blur')
    fireEvent.change(blur, { target: { value: '9' } })
    expect(screen.getByRole('button', { name: 'Custom' })).toHaveAttribute('aria-pressed', 'true')
    await userEvent.click(within(screen.getByRole('region', { name: 'Level low' })).getByRole('button', { name: '+ Add layer' }))
    expect(screen.getByRole('group', { name: 'low layer 2' })).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Remove low layer 2' }))
    expect(screen.queryByRole('group', { name: 'low layer 2' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Remove low layer 1' })).toBeDisabled()
    const name = screen.getByLabelText('Level low name')
    await userEvent.clear(name)
    await userEvent.type(name, 'flat{Enter}')
    expect(screen.getByRole('region', { name: 'Level flat' })).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: '+ Add level' }))
    expect(screen.getAllByRole('region', { name: /^Level / })).toHaveLength(4)
  })

  it('elevation: Untitled has none, so no tab and a plain message', async () => {
    at('/v2/elevation')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    expect(screen.queryByRole('link', { name: 'Elevation' })).not.toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('no elevation')
  })

  it('export lists the shadows next to the collections', async () => {
    at('/v2')
    await userEvent.click(screen.getByRole('button', { name: 'Export' }))
    const dialog = screen.getByRole('dialog', { name: /Export Default/ })
    for (const c of ['Primitives', 'Semantic', 'Type', 'Spacing', 'Grid']) await userEvent.click(within(dialog).getByRole('checkbox', { name: new RegExp(`^${c}`) }))
    expect(within(dialog).getByRole('checkbox', { name: /Elevation/ })).toBeChecked()
    expect(within(dialog).getByLabelText('Export preview')).toHaveTextContent('--elevation-xs:')
    expect(within(dialog).getByText(/^5 tokens/)).toBeInTheDocument()
  })

  it('export includes the type collection', async () => {
    at('/v2')
    await userEvent.click(screen.getByRole('button', { name: 'Export' }))
    const dialog = screen.getByRole('dialog', { name: /Export Default/ })
    expect(within(dialog).getByRole('checkbox', { name: /Type/ })).toBeChecked()
    await userEvent.click(within(dialog).getByRole('checkbox', { name: /Primitives/ }))
    await userEvent.click(within(dialog).getByRole('checkbox', { name: /Semantic/ }))
    expect(within(dialog).getByLabelText('Export preview')).toHaveTextContent('--type-heading-xl-size:')
  })

  it('import: choose the collection files, see what was found, add the system', async () => {
    const mk = (name: string, modes: Record<string, string>, variables: unknown[]) => new File([JSON.stringify({ id: name, name, modes, variables })], `${name}.json`, { type: 'application/json' })
    const col = (id: string, name: string, v: number) => ({ id, name, type: 'FLOAT', resolvedValuesByMode: { m: { resolvedValue: v, alias: null } } })
    const colour = (id: string, name: string, c: number) => ({ id, name, type: 'COLOR', resolvedValuesByMode: { m: { resolvedValue: { r: c, g: c, b: c, a: 1 }, alias: null } } })
    const steps = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
    const ramp = mk('Ramps', { m: 'Style' }, steps.map((x, i) => colour(`c${i}`, `Colors/Teal/${x}`, 1 - i / 12)))
    const radius = mk('Radius', { m: 'Mode 1' }, [col('r1', 'radius-sm', 4), col('r2', 'radius-md', 8)])
    at('/v2/import')
    await userEvent.upload(screen.getByLabelText(/Choose the JSON files/), [ramp, radius, new File(['not json'], 'bad.json')])
    expect(await screen.findByRole('table', { name: 'What was found' })).toBeInTheDocument()
    const table = within(screen.getByRole('table', { name: 'What was found' }))
    expect(table.getByRole('row', { name: /Ramps.*Colour ramps.*11/ })).toBeInTheDocument()
    expect(table.getByRole('row', { name: /Radius.*Sizes.*2/ })).toBeInTheDocument()
    expect(screen.getByText('bad.json is not valid JSON.')).toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('1 colour ramps · no type · sizes: Radius')
    fireEvent.change(screen.getByLabelText('Name'), { target: { value: 'Acme' } })
    await userEvent.click(screen.getByRole('button', { name: 'Add design system' }))
    expect(useV2.getState().activeSystemId).toBe('imported-acme')
    expect(screen.getByRole('button', { name: 'Acme' })).toHaveAttribute('aria-pressed', 'true')
    expect(within(screen.getByRole('main')).getByRole('region', { name: 'Teal' })).toBeInTheDocument()
    expect(within(within(screen.getByRole('main')).getByRole('region', { name: 'Teal' })).getAllByRole('img')).toHaveLength(11)
    await userEvent.click(screen.getByRole('button', { name: 'Remove this design system' }).closest('button')!)
  })

  it('import: a file that is not a Figma collection is explained, and nothing can be added', async () => {
    at('/v2/import')
    await userEvent.upload(screen.getByLabelText(/Choose the JSON files/), new File(['{"a":1}'], 'x.json'))
    expect(await screen.findByRole('alert')).toHaveTextContent('x.json is not a Figma variable collection')
    expect(screen.queryByRole('button', { name: 'Add design system' })).not.toBeInTheDocument()
  })

  it('v2 never writes what v1 saves', async () => {
    localStorage.setItem('baseline-project', 'v1 data')
    at('/v2')
    await userEvent.click(screen.getByRole('button', { name: 'Untitled' }))
    expect(localStorage.getItem('baseline-project')).toBe('v1 data')
    expect(useV2.getState().activeSystemId).toBe('untitled')
  })
})
